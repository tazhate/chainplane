// cosmosNetworkTip queries the local node's /consensus_state to read the network tip.
func cosmosNetworkTip(ctx context.Context, rpcURL string) int64 {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rpcURL+"/consensus_state", nil)
	if err != nil {
		return 0
	}
	resp, err := rpcClient.Do(req)
	if err != nil {
		return 0
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, maxResponseBytes))

	var cs cosmosConsensusStateResponse
	if err := json.Unmarshal(body, &cs); err != nil {
		return 0
	}
	// HeightRoundStep is formatted as "30178804/0/1"
	var h, r, s int64
	_, _ = fmt.Sscanf(cs.Result.RoundState.HeightRoundStep, "%d/%d/%d", &h, &r, &s)
	return h
}

