const (

	// cosmosBlockTime is the average Cosmos Hub block interval used to estimate network tip.
	cosmosBlockTime = 6.5 // seconds
)

// --------------------------------------------------------------------------
// Type
// --------------------------------------------------------------------------

type cosmosAdapter struct {
	baseAdapter
}

// --------------------------------------------------------------------------
// Registration
// --------------------------------------------------------------------------

func init() {
	Register(nodesv1alpha1.ChainCosmos, &cosmosAdapter{
		baseAdapter: baseAdapter{livenessPort: 26657},
	})
}

